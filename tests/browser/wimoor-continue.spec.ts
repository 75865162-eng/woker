  bundle = (await build({ entryPoints: ['tests/browser/wimoor-continue-harness.tsx'], bundle: true, write: false, platform: 'browser', format: 'iife', jsx: 'automatic', define: { 'process.env': '{"NODE_ENV":"development"}' } })).outputFiles[0].text;
