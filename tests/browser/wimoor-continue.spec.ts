async function setup(page: Page, readOnly = false) {
  const calls: Array<{ url: URL; method: string; body: Record<string, unknown> | null; workspace?: string }> = [];
  const state = { denied: false, conflict: true, failDraft: true };
  const order = { id: 'fixture-transfer', number: 'TR-FIXTURE-01', revision: 7, createdBy: 'fixture-user', createdAt: '2026-11-12T00:00:00Z', reason: '隔离调拨凭据', status: 'PARTIALLY_SHIPPED', lines: [{ id: 'fixture-line', sourceBalanceId: 'fixture-balance', targetLocationId: 'fixture-target', quantity: 10, shippedQty: 6, receivedQty: 2, source: { location: { code: 'FROM-01' }, lot: { lotCode: 'LOT-FIXTURE' } }, target: { code: 'TO-02' } }] };
  await page.route('**/*', async route => {
    const req = route.request(), url = new URL(req.url());
    expect(url.origin).toBe('http://127.0.0.1:43229');
    if (url.pathname === '/bundle.js') return route.fulfill({ contentType: 'text/javascript', body: bundle });
    if (url.pathname === '/styles.css') return route.fulfill({ contentType: 'text/css', body: styles });
    if (!url.pathname.startsWith('/api/')) return route.fulfill({ contentType: 'text/html', body: '<html><head><link rel="stylesheet" href="/styles.css"></head><body><div id="root"></div><script src="/bundle.js"></script></body></html>' });
    const body = req.method() === 'GET' ? null : req.postDataJSON();
    calls.push({ url, body, method: req.method(), workspace: req.headers()['x-workspace-id'] });
    if (url.pathname === '/api/workspaces') return route.fulfill({ json: { workspaces: [{ id: 'fixture-workspace', name: '隔离仓库' }, { id: 'other-fixture', name: '另一隔离工作区' }] } });
    if (state.denied) return route.fulfill({ status: 403, json: { error: '隔离测试：权限已撤回' } });
    if (url.pathname === '/api/operations/wms/balances') return route.fulfill({ json: { items: [{ id: 'fixture-balance', available: 20, stock: { warehouseCode: 'WH-FIXTURE', locationCode: 'FROM-01', lotCode: 'LOT-FIXTURE' } }], nextCursor: null } });
    if (url.pathname === '/api/operations/wms/locations') return route.fulfill({ json: { items: [{ id: 'fixture-target', code: 'TO-02', warehouseId: 'fixture-wh', kind: 'STORAGE', enabled: true, frozen: false }], nextCursor: null } });
    if (url.pathname === '/api/operations/wms/approvals' && req.method() === 'POST') return state.conflict ? route.fulfill({ status: 409, json: { error: '隔离测试：调拨版本冲突' } }) : route.fulfill({ json: { item: { id: 'fixture-approval' } } });
    if (url.pathname === '/api/operations/wms/transfer-orders') {
      if (req.method() === 'POST') return state.failDraft ? route.fulfill({ status: 422, json: { error: '隔离测试：计划数量超过可用库存' } }) : route.fulfill({ json: { item: { id: order.id } } });
      const matches = !url.searchParams.get('status') || url.searchParams.get('status') === order.status;
      return route.fulfill({ json: { items: matches && !url.searchParams.get('cursor') ? [order] : [], nextCursor: matches && !url.searchParams.get('cursor') ? 'fixture-cursor' : null } });
    }
    if (url.pathname === '/api/operations/wms/approvals') return route.fulfill({ json: { items: [], nextCursor: null } });
    throw Error('Unexpected request: ' + url.pathname);
  });
  await page.goto('http://127.0.0.1:43229/logistics/warehouse?tab=transfer-orders' + (readOnly ? '&readonly=1' : ''));
  await expect(page.getByRole('table', { name: '在途调拨单列表' })).toContainText(order.number);
  return { calls, state };
}
