import assert from 'node:assert/strict';
import {expect,type Page,type Locator} from '@playwright/test';
import {prisma} from '../../src/lib/db/prisma';
export async function verifyBrowserCustomsFinance(page:Page,card:Locator){
 await card.getByRole('button',{name:'修改费用分摊',exact:true}).click();
 const costForm=page.getByRole('form',{name:'头程费用分摊',exact:true});
 await costForm.getByLabel('按货件箱SKU分层分摊',{exact:true}).check();
 const plan=await prisma.fbaLocalPlan.findFirstOrThrow({where:{number:'BROWSER-CORE'},include:{lines:{orderBy:{id:'asc'}},shipments:true}});
 await costForm.getByLabel('箱BROWSER-BOX所属货件',{exact:true}).selectOption(plan.shipments[0].id);
 await costForm.getByRole('button',{name:'计算并保存费用草稿',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'头程费用分摊',exact:true})).toHaveCount(0);
 const updated=await prisma.fbaLocalPlan.findUniqueOrThrow({where:{id:plan.id}});
 assert.ok(updated.costAllocation&&typeof updated.costAllocation==='object'&&!Array.isArray(updated.costAllocation)&&updated.costAllocation.hierarchy);
 await card.getByRole('button',{name:'新增报关资料',exact:true}).click();
 const customs=page.getByRole('form',{name:'报关资料草稿',exact:true});
 await customs.getByLabel('报关关联货件',{exact:true}).selectOption(plan.shipments[0].id);
 for(const [label,value]of [['报关资料编号','BROWSER-CUSTOMS'],['目的国代码','US'],['申报币种','USD'],['出口方','Synthetic Exporter'],['进口方','Synthetic Importer'],['申报模板来源','Synthetic internal template'],['申报资料依据','Synthetic invoice']])await customs.getByLabel(label,{exact:true}).fill(value);
 for(const [index] of plan.lines.entries())for(const [label,value]of [['申报品名',`Synthetic item ${index+1}`],['HS 编码','123456'],['原产国代码','CN'],['申报单位','PCS'],['申报单价','3.123456']])await customs.getByLabel(`明细${index+1}${label}`,{exact:true}).fill(value);
 await customs.getByRole('button',{name:'保存报关草稿',exact:true}).click();
 await expect(card.getByLabel('报关资料与清关登记')).toContainText('BROWSER-CUSTOMS');
 await card.getByRole('button',{name:'登记货件资料',exact:true}).click();
 const documents=page.getByRole('form',{name:'货件资料登记',exact:true});
 await documents.getByLabel('资料关联货件',{exact:true}).selectOption(plan.shipments[0].id);
 for(const [label,value]of [['货件资料编号','BROWSER-APPOINTMENT'],['货件资料依据','Synthetic booking receipt'],['预约开始（含时区）','2026-11-12T12:00:00Z'],['预约结束（含时区）','2026-11-12T14:00:00Z'],['预约地点/仓库依据','Synthetic facility'],['预约回执号','Synthetic booking']])await documents.getByLabel(label,{exact:true}).fill(value);
 await documents.getByRole('button',{name:'保存货件资料',exact:true}).click();
 await expect(card.getByLabel('预约保单与柜单')).toContainText('BROWSER-APPOINTMENT');
 await card.getByRole('button',{name:'编制费用调整草稿',exact:true}).click();
 const finance=page.getByRole('form',{name:'费用调整规则',exact:true});
 for(const [label,value]of [['拟用账套名称/编号','Synthetic Proposed Book'],['拟用期间编号','2026'],['期间开始日期','2026-01-01'],['期间结束日期','2026-12-31'],['拟用会计日期','2026-11-12'],['拟用应付科目编号','2202'],['核算规则依据','Synthetic proposed policy']])await finance.getByLabel(label,{exact:true}).fill(value);
 for(const [index] of plan.lines.entries())await finance.getByLabel(`明细${index+1}拟用成本科目`,{exact:true}).fill('1405');
 await finance.getByRole('checkbox',{name:/本次规则计算将上述科目/}).check();
 await finance.getByRole('button',{name:'生成并保存凭证草稿',exact:true}).click();
 await expect(card.getByLabel('费用差异凭证草稿')).toContainText('Synthetic Proposed Book');
 await page.reload({waitUntil:'domcontentloaded'});
 await page.getByLabel('店铺',{exact:true}).selectOption('seller');
 await page.getByLabel('站点',{exact:true}).selectOption('SITE');
 await expect(card.getByLabel('报关资料与清关登记')).toContainText('BROWSER-CUSTOMS');
 await expect(card.getByLabel('费用差异凭证草稿')).toContainText('借方 10.000000 / 贷方 10.000000');
 assert.equal(await prisma.fbaLocalCustomsDeclaration.count({where:{planId:plan.id}}),1);
 const adjustment=await prisma.fbaLocalCostAdjustment.findFirstOrThrow({where:{bill:{fee:{planId:plan.id}}},include:{drafts:true}});
 assert.equal(adjustment.drafts.length,1);assert.equal(adjustment.drafts[0].status,'DRAFT_RULES');
 console.log('PASS: browser hierarchical costs, customs data and proposed accounting voucher save and survive reload');
}
