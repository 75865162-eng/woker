export const SKILLS = ["amazon-niche-finder", "amazon-product-research", "amazon-review-analyzer", "tariff-calculator-amazon", "amazon-product-selection"] as const;
export type Status = "CREATED" | "RUNNING" | "WAITING_FOR_USER" | "RESUMABLE" | "COMPLETED" | "FAILED" | "CANCELLED";
export type Json = null | boolean | number | string | Json[] | { [key: string]: Json };
export type ObjectJson = { [key: string]: Json };
export interface Scope { organizationId: string; workspaceId: string; ownerId: string }
export interface SkillSnapshot { name: string; path: string; sha256: string; markdown: string; tools: string[] }
export interface ToolDefinition { name: string; description?: string; inputSchema: ObjectJson; annotations?: { readOnlyHint?: boolean } }
/** Reviewed policy is host input, never generated by the model. Amounts use integer provider units. */
export interface ToolPolicy { provider: string; paid: boolean; units: number; unit: "calls" | "credits"; pricingSource: string; maxCalls: number; stages: number[] }
export interface CallRecord {
  id: string; projectId: string; stage: number; skill: string; service: "lili" | "sellersprite"; provider: string; tool: string;
  arguments: ObjectJson; requestedAt: string; respondedAt?: string; status: "IN_FLIGHT" | "SUCCEEDED" | "FAILED" | "UNKNOWN";
  paid: boolean; reservedUnits: number; billing: "FREE" | "UNKNOWN" | "CONFIRMED"; knownUnits?: number;
  retryCount: number; rawResponse?: Json; errorCode?: string;
  inputSchema: ObjectJson;
}
export interface Claim {
  text: string; kind: "observed" | "calculated" | "estimated" | "assumption"; evidenceIds: string[];
  formula?: string; sourceUrl?: string; applicableDate?: string; topic?: "tariff";
}
export interface StageResult { summary: string; claims: Claim[]; candidates?: { id: string; name: string }[]; verdict?: "GO" | "NO_GO" | "NEEDS_VALIDATION" }
export type Action = { type: "call"; tool: string; arguments: ObjectJson } | { type: "complete"; result: StageResult };
export interface Gate { id: string; kind: "NICHE" | "FINAL" | "BUDGET" | "BILLING" | "MCP_CALL"; reason: string }
export interface Decision { gateId: string; kind: "SELECT" | "CONFIRM" | "INCREASE_BUDGET" | "RECONCILE" | "AUTHORIZE_TOOL"; candidateId?: string; limits?: Record<string, number>; toolMaxCalls?: Record<string, number>; callId?: string; units?: number; receipt?: string }
export interface Run {
  version: 1; id: string; revision: number; scope: Scope; requirement: string; marketplace: string; mode: "live" | "fixture";
  createdAt: string; updatedAt: string; status: Status; stage: number; skills: SkillSnapshot[];
  registry: ToolDefinition[]; registryAt?: string; policies: Record<string, ToolPolicy>; limits: Record<string, number>;
  calls: CallRecord[]; results: StageResult[]; gate?: Gate; selectedCandidateId?: string; pendingActionId?: string;
  decisions: { actorId: string; at: string; decision: Decision }[]; failure?: string;
  actions: { at: string; stage: number; action: Action }[];
  pendingAction?: Extract<Action, { type: "call" }>; pendingActionFingerprint?: string; pendingActionApproved?: boolean;
  report?: { fileId: string; savedAt: string };
}
export interface ResearchContext { run: Run; skill: SkillSnapshot; tools: ToolDefinition[]; instructions: string }
export interface Agent { next(context: ResearchContext): Promise<Action> }
export interface Transport { listTools(): Promise<ToolDefinition[]>; callTool(name: string, args: ObjectJson, signal: AbortSignal, expectedSchema?: ObjectJson): Promise<Json> }
export interface Store { transaction<T>(id: string, work: (run: Run, save: () => Promise<void>) => Promise<T>): Promise<T>; create(run: Run): Promise<void>; read(id: string): Promise<Run> }
