/**
 * 赛狐承接页目录：一个业务模块一页，页内按数据集切 tab。
 *
 * 设计约束（与 docs/sellfox-full-sync-plan.md 对齐）：
 * - 每个数据集只出现在一个页面里，页面负责声明来源、时间口径、落表与优先级。
 * - status = "live" 才允许读取；"planned" / "blocked" 只渲染「未接入」说明，不造行、不补 0。
 * - api 只写能核对到的真实路径；没抓到文档的接口写「文档：接口名」。
 */

export type HostStatus = "live" | "planned" | "blocked";
export type HostPriority = "P0" | "P1" | "P2";
export type HostColumnKind = "text" | "stack" | "qty" | "decimal" | "money" | "rate" | "date" | "store" | "tags";

export type HostColumn = {
  key: string;
  label: string;
  kind?: HostColumnKind;
  /** 次行字段（kind = "stack" 时使用）。 */
  sub?: string;
  hint?: string;
  width?: number;
};

export type HostDataset = {
  id: string;
  label: string;
  status: HostStatus;
  priority: HostPriority;
  /** 落表名，未接入时也写目标表，方便对照规划。 */
  table: string;
  api: string[];
  /** 时间口径说明，显示在页面头部与 tab tooltip。 */
  grain: string;
  note?: string;
  /** live 数据集的读取方式：直连已有接口，或走 host-read 注册表。 */
  endpoint?: string;
  reader?: string;
  columns: HostColumn[];
  /** 是否支持站点/店铺/搜索/日期筛选。 */
  searchable?: boolean;
  dateRange?: boolean;
  /** 广告类数据集才有 adType（sp/sb/sd）。 */
  adType?: boolean;
};

export type HostPage = {
  id: string;
  href: string;
  title: string;
  subtitle: string;
  /** 页面级来源徽标，全部是赛狐侧数据，不与 Amazon SP-API 混算。 */
  source: string;
  datasets: HostDataset[];
};

